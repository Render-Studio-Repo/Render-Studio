def resolve_frontend_rel(full_path: str) -> str:
    raw = str(full_path or "").lstrip("/")
    if raw.startswith("_archive/") or "/_archive/" in raw or ".bak" in Path(raw).name:
        return raw  # caller should 404 archive/bak
    if raw in ALIASES:
        return ALIASES[raw]
    name = raw.split("/")[-1]
    if name in ALIASES and "/" not in raw:
        return ALIASES[name]
    return raw
