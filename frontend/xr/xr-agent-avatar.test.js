import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { agentControllerSideLocal } from "./xr-agent-avatar.js";

test("AI and mic sit on the inner analog-stick side of the right controller", () => {
  const right = agentControllerSideLocal({ pointingIsRight: true });
  const left = agentControllerSideLocal({ pointingIsRight: false });
  assert.ok(right.x < 0, "right inner side is -X");
  assert.ok(left.x > 0, "left inner side is +X");
  assert.ok(Math.abs(right.x) < 0.028, "tighter to the controller body, not hanging off");
  assert.ok(right.y > 0.03, "analog-stick height, not down the handle");
  assert.ok(right.y < 0.05, "not floating above the analog cluster");
  assert.ok(right.z > 0, "not in the -Z aim laser");
  assert.ok(right.z < 0.01, "flush to the grip mesh");
  assert.ok(right.aiY > right.micY, "AI sits above the mic on the same face");
  assert.ok(Math.abs(right.ry) > 1, "buttons face sideways, not the back of the controller");
  const src = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "xr-agent-avatar.js"), "utf8");
  assert.equal(src.includes(".045,-.05,.065"), false);
  assert.ok(src.includes("agent:mic"));
  assert.match(src, /scene\.add\(wrist\);[\s\S]{0,180}wrist\.visible=false/);
  assert.ok(src.includes("22c55e"));
  assert.ok(src.includes("ef4444"));
  const xr = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "viewport-xr.js"), "utf8");
  assert.ok(xr.includes("agent:mic"));
  assert.ok(xr.includes("toggleHeadsetMic"));
  const palette = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "xr-hand-palette.js"), "utf8");
  assert.ok(palette.includes("0x22c55e"));
  assert.ok(palette.includes("0xef4444"));
  assert.ok(src.includes("voice:sample"));
  assert.ok(src.includes("Listen"));
  assert.ok(src.includes("agent:sample-voice"));
  assert.equal(src.includes("createVoiceMold"), false);
});

test("VR agent setting toggles persist without pressing Save", () => {
  const src = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "xr-agent-avatar.js"), "utf8");
  assert.ok(src.includes("function commitTextEdit"));
  assert.ok(src.includes("onAction?.('agent:setting'"));
  assert.match(src, /if\(id==='agent:close'\)\{commitTextEdit\(\)/);
  assert.match(src, /showToRoom.*shareWithRoom.*allowOtherUsersTrigger/);
  assert.ok(src.includes("onAction?.('agent:setting',{[id]:!s[id]})"));
  const closeBeforeSave = src.indexOf("if(id==='agent:close'){commitTextEdit()");
  const saveKey = src.indexOf("k==='done'");
  assert.ok(closeBeforeSave > 0 && saveKey > 0);
  const bridge = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "../components/xr-agent-bridge.js"), "utf8");
  assert.ok(bridge.includes("createXrAgentLiveAccountStorage"));
  assert.ok(bridge.includes("xrAgentRemoteSyncDelayMs"));
  assert.ok(bridge.includes("delay<=0)void push()"));
  const settings = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "../components/xr-agent-settings.js"), "utf8");
  assert.ok(settings.includes("function persistField"));
  assert.ok(settings.includes("flushPersists()"));
  assert.ok(settings.includes('delay = type === "range" || type === "text" || type === "textarea" ? 150 : 0'));
  const xr = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "viewport-xr.js"), "utf8");
  assert.ok(xr.includes("writeVoicePrefs({ wanted: true, muted: true })"));
  assert.ok(xr.includes("xrVoice.setMuted?.(!!voicePrefs.muted)"));
});
