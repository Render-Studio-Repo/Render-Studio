/**
 * Onshape Library panel — browse documents and import parts into a project.
 *
 * Usage:
 *   import { initOnshapePanel } from './onshape-panel.js';
 *   initOnshapePanel({ api, onImported });
 *     onImported(projectId, filename, name) — called after a successful import
 */

import { authHeaders, getToken } from './auth.js';

const ELEM_TYPE_LABEL = {
  PARTSTUDIO:  'Part Studio',
  ASSEMBLY:    'Assembly',
  BLOB:        'File',
  APPLICATION: 'App',
};

// 3D-importable blob extensions
const IMPORTABLE_EXTS = /\.(step|stp|stl|3mf|obj|glb|gltf)$/i;

// System/metadata element names generated by Onshape internals — not real models
const SYSTEM_NAME = /^(Open CASCADE|Default geometry|Variable Studio|BOM|Bill of Materials|Dashboard)/i;

function isImportable(el) {
  if (SYSTEM_NAME.test(el.name)) return false;
  if (el.type === 'PARTSTUDIO' || el.type === 'ASSEMBLY') return true;
  if (el.type === 'BLOB') return IMPORTABLE_EXTS.test(el.name);
  return false;
}

function shouldShow(el) {
  // Hide system elements entirely — don't even show them greyed out
  if (SYSTEM_NAME.test(el.name)) return false;
  if (el.type === 'APPLICATION') return false;
  // Blob elements only if they have a recognised 3D extension
  if (el.type === 'BLOB') return IMPORTABLE_EXTS.test(el.name);
  return true;
}

export function initOnshapePanel({ api, onImported, onView, getCurrentProjectId }) {
  const section = document.getElementById('onshape-library-section');
  if (!section) return;

  const listEl  = section.querySelector('.onshape-doc-list');
  const statusEl = section.querySelector('.onshape-status');
  const btnRefresh = section.querySelector('.btn-onshape-refresh');

  let docsCache = [];
  // Map "did:eid" → { projectId, btn } for elements that were imported this session
  const importedMap = new Map();

  // ── helpers ──────────────────────────────────────────────────────────────

  function setStatus(msg, isError = false) {
    if (!statusEl) return;
    statusEl.textContent = msg;
    statusEl.className = 'onshape-status muted small' + (isError ? ' error' : '');
  }

  function clearStatus() { if (statusEl) statusEl.textContent = ''; }

  // ── render document list ─────────────────────────────────────────────────

  function renderDocs(docs) {
    if (!listEl) return;
    listEl.innerHTML = '';
    if (!docs.length) {
      listEl.innerHTML = '<p class="muted small" style="padding:6px 0">No documents found.</p>';
      return;
    }
    for (const doc of docs) {
      const item = document.createElement('div');
      item.className = 'onshape-doc-item';
      item.dataset.did = doc.id;
      item.dataset.wid = doc.workspace_id;
      item.innerHTML = `
        <div class="onshape-doc-header">
          <span class="onshape-doc-name">${escHtml(doc.name)}</span>
          <button type="button" class="btn-icon onshape-doc-toggle" title="Show parts" aria-expanded="false">
            <svg viewBox="0 0 10 10" width="10" height="10" fill="currentColor"><path d="M2 3l3 4 3-4H2z"/></svg>
          </button>
        </div>
        <div class="onshape-doc-elements hidden"></div>
      `;
      const toggleBtn = item.querySelector('.onshape-doc-toggle');
      const elemPanel = item.querySelector('.onshape-doc-elements');

      toggleBtn.addEventListener('click', () => {
        const open = elemPanel.classList.toggle('hidden') === false;
        toggleBtn.setAttribute('aria-expanded', open);
        toggleBtn.style.transform = open ? 'rotate(0deg)' : 'rotate(-90deg)';
        if (open && !elemPanel.dataset.loaded) {
          loadElements(doc, elemPanel);
        }
      });

      listEl.appendChild(item);
    }
  }

  // ── load elements for a doc ──────────────────────────────────────────────

  async function loadElements(doc, container) {
    container.dataset.loaded = '1';
    container.innerHTML = '<p class="muted small loading-dots">Loading…</p>';
    try {
      const data = await api(
        `/api/onshape/documents/${doc.id}/elements?wid=${encodeURIComponent(doc.workspace_id)}`
      );
      renderElements(doc, data.elements || [], container);
    } catch (err) {
      container.innerHTML = `<p class="muted small error">${escHtml(err.message || 'Failed to load')}</p>`;
    }
  }

  function renderElements(doc, elements, container) {
    const visible = elements.filter(shouldShow);
    if (!visible.length) {
      container.innerHTML = '<p class="muted small">No 3D models found in this document.</p>';
      return;
    }
    container.innerHTML = '';
    for (const el of visible) {
      const canImport = isImportable(el);
      const typeLabel = ELEM_TYPE_LABEL[el.type] || el.type;
      const key = `${doc.id}:${el.id}`;
      const alreadyImported = importedMap.has(key);

      const row = document.createElement('div');
      row.className = 'onshape-elem-row' + (canImport ? '' : ' onshape-elem-row--dim');
      row.dataset.elemKey = key;
      const imp = importedMap.get(key);
      row.innerHTML = `
        <span class="onshape-elem-type-badge">${escHtml(typeLabel)}</span>
        <span class="onshape-elem-name">${escHtml(el.name)}</span>
        <div class="onshape-elem-btns">
          ${alreadyImported ? `
            <button type="button" class="btn btn-compact btn-onshape-view" title="Switch to this model in the viewport">View</button>
            <button type="button" class="btn btn-compact btn-onshape-push" title="Push current edits back to Onshape">
              <img src="/onshape-logo.png" width="11" height="11" alt="" style="vertical-align:-1px" /> Push
            </button>
          ` : `
            <button type="button" class="btn btn-compact btn-onshape-import"
              ${canImport ? '' : 'disabled title="Not a 3D model"'}>Import</button>
          `}
        </div>
      `;
      if (canImport) {
        if (alreadyImported) {
          row.querySelector('.btn-onshape-view')?.addEventListener('click', () => {
            onView?.(imp.projectId, imp.filename, imp.name);
          });
          row.querySelector('.btn-onshape-push')?.addEventListener('click', (e) => {
            pushElement(imp.projectId, el.name, e.currentTarget);
          });
        } else {
          row.querySelector('.btn-onshape-import')?.addEventListener('click', () => importElement(doc, el, row, key));
        }
      }
      container.appendChild(row);
    }
  }

  // ── import a single element ──────────────────────────────────────────────

  async function importElement(doc, el, row, key) {
    const importBtn = row.querySelector('.btn-onshape-import');
    importBtn.disabled = true;
    importBtn.textContent = el.type === 'BLOB' ? 'Downloading…' : 'Converting…';

    let dotInterval = null;
    if (el.type !== 'BLOB') {
      let dots = 0;
      const labels = ['Converting.', 'Converting..', 'Converting...', 'Converting'];
      dotInterval = setInterval(() => { importBtn.textContent = labels[dots++ % labels.length]; }, 700);
    }

    try {
      const res = await fetch('/api/onshape/import', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', ...authHeaders() },
        body: JSON.stringify({
          document_id:    doc.id,
          workspace_id:   doc.workspace_id,
          element_id:     el.id,
          element_type:   el.type,
          name:           el.name || doc.name,
          document_name:  doc.name,
        }),
      });
      if (!res.ok) {
        const d = await res.json().catch(() => ({}));
        throw new Error(d.detail || `Import failed (${res.status})`);
      }
      const result = await res.json();
      clearInterval(dotInterval);
      importBtn.textContent = 'Imported ✓';
      importBtn.classList.add('success');

      // Track this import so we can show View + Push buttons
      importedMap.set(key, { projectId: result.project_id, filename: result.filename, name: result.name });

      // Replace Import button area with View + Push buttons
      const btns = row.querySelector('.onshape-elem-btns');
      if (btns) {
        btns.innerHTML = `
          <button type="button" class="btn btn-compact btn-onshape-view" title="Switch to this model in the viewport">View</button>
          <button type="button" class="btn btn-compact btn-onshape-push" title="Push current edits back to Onshape">
            <img src="/onshape-logo.png" width="11" height="11" alt="" style="vertical-align:-1px" /> Push
          </button>
        `;
        btns.querySelector('.btn-onshape-view').addEventListener('click', () => {
          onView?.(result.project_id, result.filename, result.name);
        });
        btns.querySelector('.btn-onshape-push').addEventListener('click', (e) => {
          pushElement(result.project_id, el.name, e.currentTarget);
        });
      }

      onImported?.(result.project_id, result.filename, result.name);
    } catch (err) {
      clearInterval(dotInterval);
      importBtn.disabled = false;
      importBtn.textContent = 'Import';
      alert(err.message || 'Import failed');
    }
  }

  // ── push edits back to Onshape ───────────────────────────────────────────

  async function pushElement(projectId, elementName, btn) {
    if (!projectId) { alert('No project linked — import first.'); return; }
    const orig = btn.innerHTML;
    btn.disabled = true;
    btn.innerHTML = `<img src="/onshape-logo.png" width="11" height="11" alt="" style="vertical-align:-1px" /> Pushing…`;
    try {
      const res = await fetch(`/api/projects/${projectId}/push-to-onshape`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', ...authHeaders() },
        body: JSON.stringify({}),
      });
      if (!res.ok) {
        const d = await res.json().catch(() => ({}));
        throw new Error(d.detail || `Push failed (${res.status})`);
      }
      const data = await res.json();

      // Replace Push button with a "Open in Onshape" link — don't auto-open
      // Onshape needs 1-3 min to translate large STEP files
      const btns = btn.closest('.onshape-elem-btns');
      if (btns) {
        btn.remove();
        const link = document.createElement('a');
        link.href = data.url;
        link.target = '_blank';
        link.rel = 'noopener';
        link.className = 'btn btn-compact btn-onshape-push success';
        link.style.textDecoration = 'none';
        link.innerHTML = `<img src="/onshape-logo.png" width="11" height="11" alt="" style="vertical-align:-1px" /> Open in Onshape`;
        link.title = 'Onshape is processing the STEP file — click to open once ready (may take 1–2 min for large models)';
        btns.appendChild(link);
      }
    } catch (err) {
      btn.disabled = false;
      btn.innerHTML = orig;
      alert(err.message || 'Push failed');
    }
  }

  // ── load documents ───────────────────────────────────────────────────────

  function renderDisconnected() {
    setStatus("Sign in with Onshape to browse your documents.");
    if (!listEl) return;
    listEl.innerHTML = `
      <div class="cloud-library-connect">
        <p class="muted small">Link Onshape to browse documents and import Part Studios or assemblies into Render3D.</p>
        <button type="button" class="btn primary btn-compact btn-cloud-connect-now" data-cloud="onshape">
          <img src="/onshape-logo.png?v=20260617-small" width="14" height="14" alt="" />
          Connect now
        </button>
      </div>
    `;
    listEl.querySelector(".btn-cloud-connect-now")?.addEventListener("click", () => {
      const profileBtn = document.getElementById("btn-onshape-connect");
      if (profileBtn) {
        profileBtn.click();
        return;
      }
      void startOnshapeConnect();
    });
  }

  async function startOnshapeConnect() {
    try {
      const res = await fetch("/api/onshape/oauth-url", {
        method: "POST",
        headers: authHeaders(),
      });
      const data = await res.json().catch(() => ({}));
      if (!res.ok) throw new Error(data.detail || `Could not start Onshape connect (${res.status})`);
      const url = data.url || "/oauth/start";
      window.open(url, "render3d-onshape-connect", "popup=yes,width=720,height=820");
    } catch (err) {
      setStatus(err.message || "Could not start Onshape connection.", true);
      window.open("/oauth/start", "render3d-onshape-connect", "popup=yes,width=720,height=820");
    }
  }

  async function loadDocuments() {
    if (!listEl) return;
    listEl.innerHTML = "";
    setStatus("Loading your Onshape documents…");
    try {
      // Prefer an explicit status check so we can show Connect now immediately.
      try {
        const statusRes = await fetch("/api/onshape/status", { headers: authHeaders() });
        if (statusRes.ok) {
          const status = await statusRes.json();
          if (!status?.linked) {
            renderDisconnected();
            return;
          }
        }
      } catch {
        /* fall through to documents fetch */
      }

      const data = await api("/api/onshape/documents?limit=30");
      docsCache = data.documents || [];
      clearStatus();
      renderDocs(docsCache);
    } catch (err) {
      if (/not linked|401|not authenticated/i.test(err.message || "")) {
        renderDisconnected();
      } else {
        setStatus(err.message || "Could not load documents.", true);
      }
    }
  }

  btnRefresh?.addEventListener("click", () => loadDocuments());

  window.addEventListener("message", (event) => {
    if (event.origin !== window.location.origin) return;
    if (!event.data || event.data.type !== "render3d:oauth-done") return;
    if (String(event.data.provider || "").toLowerCase() !== "onshape") return;
    if (event.data.ok) loadDocuments();
  });

  // Auto-load when the section becomes visible (IntersectionObserver)
  const observer = new IntersectionObserver((entries) => {
    if (entries[0].isIntersecting) {
      observer.disconnect();
      loadDocuments();
    }
  }, { threshold: 0.1 });
  observer.observe(section);
}

function escHtml(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
