export function featuresByCategory() {
  return DOC_CATEGORIES.map((cat) => ({
    ...cat,
    features: DOC_FEATURES.filter((f) => f.category === cat.id),
  })).filter((row) => row.features.length);
}

export function getDocFeature(id) {
  return DOC_FEATURES.find((f) => f.id === id) || null;
}
