test("context lost/restored stamp webgl.context, never viewport.boot", () => {
  assert.equal(studioSmokeFeature("webglcontextlost"), "webgl.context");
  assert.equal(studioSmokeStatus("webglcontextlost"), "broken");
  assert.equal(studioSmokeFeature("webglcontextrestored"), "webgl.context");
  assert.equal(studioSmokeStatus("webglcontextrestored"), "ok");
  assert.notEqual(studioSmokeFeature("webglcontextlost"), "viewport.boot");
  assert.equal(studioSmokeFeature("boot"), "viewport.boot");
  assert.equal(studioSmokeStatus("boot", true), "ok");
});

test("fetch/ws failures map timeout/dns/throttle vs networking", () => {
  assert.equal(studioNetworkKind({ name: "AbortError", kind: "fetch.fail" }), "network.timeout");
  assert.equal(studioSmokeFeature("timeout"), "network.timeout");
  assert.equal(studioSmokeFeature("fetch.fail", { message: "ERR_NAME_NOT_RESOLVED" }), "network.dns");
  assert.equal(studioSmokeFeature("dns"), "network.dns");
  assert.equal(studioSmokeFeature("fetch.fail", { status: 429 }), "network.throttle");
  assert.equal(studioSmokeFeature("throttle"), "network.throttle");
  assert.equal(studioSmokeFeature("websocket.error"), "network.latency");
  assert.equal(studioSmokeFeature("websocket.fail"), "network.latency");
  assert.equal(studioSmokeFeature("fetch.fail", { message: "Failed to fetch" }), "network.latency");
  assert.equal(studioSmokeStatus("fetch.fail"), "broken");
  assert.equal(studioSmokeStatus("network.timeout"), "broken");
});

