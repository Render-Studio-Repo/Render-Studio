/** Share-page History author avatars → public profile popup. */

export const SHARE_HISTORY_PROFILE_KIND = "share-history-profile";

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (ch) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  }[ch]));
}

export function shareHistoryAuthorId(entry = {}) {
  return String(entry.user_id || entry.author_id || entry.userId || "").trim();
}

export function shareHistoryOwnerEntry(meta = {}) {
  const src = meta.generated_by || meta.shared_by || {};
  return {
    user_id: src.user_id || src.id || "",
    user_name: src.display_name || src.user_name || "",
    user_avatar_url: src.avatar_url || "",
    handle: src.handle || "",
  };
}

export function shareHistoryAuthorName(entry = {}) {
  return String(entry.user_name || entry.author_name || entry.display_name || "").trim();
}

export function shareHistoryAvatarUrl(entry = {}) {
  const stored = String(entry.user_avatar_url || entry.avatar_url || "").trim();
  if (stored) return stored;
  const userId = shareHistoryAuthorId(entry);
  return userId ? `/api/users/${encodeURIComponent(userId)}/avatar` : "";
}

export function shareHistorySignInReturnTo({
  pathname = "",
  userId = "",
  handle = "",
  intent = "",
} = {}) {
  const path = String(pathname || "").startsWith("/share/")
    ? String(pathname)
    : `/share/${encodeURIComponent(String(pathname || "").replace(/^\/share\//, ""))}`;
  const params = new URLSearchParams();
  params.set("open_history", "1");
  if (userId) params.set("profile", String(userId));
  if (handle) params.set("profile_handle", String(handle).replace(/^@/, ""));
  if (intent) params.set("profile_intent", String(intent));
  return `${path}?${params.toString()}`;
}

export function shareHistoryAvatarHtml(entry = {}) {
  const userId = shareHistoryAuthorId(entry);
  const handle = String(entry.handle || entry.user_handle || "").replace(/^@/, "").trim();
  const name = shareHistoryAuthorName(entry);
  const url = shareHistoryAvatarUrl(entry);
  const initial = (name || handle || "?").trim().charAt(0).toUpperCase() || "?";
  if (!userId && !name && !handle) return "";
  const cls = `sv-avatar${url ? "" : " sv-avatar--initial"}${userId || handle ? " sv-avatar--profile" : ""}`;
  const style = url ? ` style="background-image:url('${escapeHtml(url)}')"` : "";
  const inner = url ? "" : escapeHtml(initial);
  const label = name ? `View public profile for ${name}` : "View public profile";
  if (userId || handle) {
    const idAttr = userId ? ` data-share-profile-id="${escapeHtml(userId)}"` : "";
    const handleAttr = handle ? ` data-share-profile-handle="${escapeHtml(handle)}"` : "";
    return `<button type="button" class="${cls}"${idAttr}${handleAttr} title="${escapeHtml(label)}" aria-label="${escapeHtml(label)}"${style}>${inner}</button>`;
  }
  return `<span class="${cls}" aria-hidden="true"${style}>${inner}</span>`;
}

export function shareHistoryWhoRowHtml(entry = {}, { prefix = "Generated by" } = {}) {
  const name = shareHistoryAuthorName(entry);
  const userId = shareHistoryAuthorId(entry);
  const handle = String(entry.handle || entry.user_handle || "").replace(/^@/, "").trim();
  const avatar = shareHistoryAvatarHtml(entry);
  if (!avatar) return "";
  const who = name
    ? `${prefix ? `${escapeHtml(prefix)} ` : ""}<strong>${escapeHtml(name)}</strong>`
    : handle
      ? `${prefix ? `${escapeHtml(prefix)} ` : ""}<strong>@${escapeHtml(handle)}</strong>`
      : escapeHtml(prefix || "Author");
  return `<div class="sv-history-who">${avatar}<span>${who}</span></div>`;
}

export function shareHistoryCommentCardHtml(row = {}) {
  const who = shareHistoryWhoRowHtml({
    user_id: row.author_id || row.user_id,
    user_name: row.author_name || row.user_name || "Guest",
    user_avatar_url: row.avatar_url || row.user_avatar_url,
    handle: row.handle,
  }, { prefix: "" });
  const t = Math.max(0, Number(row.t || 0));
  return `<article class="sv-history-card sv-history-card--seek" data-share-seek="${t}">${who}<button type="button" class="sv-history-time" data-share-seek="${t}">${t.toFixed(1)}s</button><div>${escapeHtml(row.text || "")}</div></article>`;
}

export function bindShareHistoryProfileClicks(root, onOpen) {
  if (!root || typeof onOpen !== "function" || root.dataset.shareProfileBound === "1") return root;
  root.dataset.shareProfileBound = "1";
  root.addEventListener("click", (event) => {
    const btn = event.target.closest?.("[data-share-profile-id], [data-share-profile-handle]");
    if (!btn || !root.contains(btn)) return;
    const userId = btn.getAttribute("data-share-profile-id") || "";
    const handle = btn.getAttribute("data-share-profile-handle") || "";
    if (!userId && !handle) return;
    event.preventDefault();
    event.stopPropagation();
    onOpen({ userId, handle, anchor: btn });
  });
  return root;
}
