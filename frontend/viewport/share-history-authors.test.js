import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  SHARE_HISTORY_PROFILE_KIND,
  bindShareHistoryProfileClicks,
  shareHistoryAvatarHtml,
  shareHistoryCommentCardHtml,
  shareHistoryOwnerEntry,
  shareHistorySignInReturnTo,
  shareHistoryWhoRowHtml,
} from "./share-history-authors.js";

const here = dirname(fileURLToPath(import.meta.url));
const shareViewer = readFileSync(join(here, "share-viewer.js"), "utf8");
const shareHtml = readFileSync(join(here, "../pages/share.html"), "utf8");
const profileJs = readFileSync(join(here, "../components/user-profile.js"), "utf8");
const app = readFileSync(join(here, "../studio/app.js"), "utf8");

test("history avatars are clickable profile buttons with Add/Message popup wiring", () => {
  const html = shareHistoryAvatarHtml({
    user_id: "u-sam",
    user_name: "Sam",
    user_avatar_url: "/api/users/u-sam/avatar",
  });
  assert.match(html, /data-share-profile-id="u-sam"/);
  assert.match(html, /sv-avatar--profile/);
  assert.match(html, /View public profile for Sam/);
  assert.match(html, /\/api\/users\/u-sam\/avatar/);
  const who = shareHistoryWhoRowHtml({ user_id: "u-sam", user_name: "Sam" });
  assert.match(who, /Generated by/);
  assert.match(who, /<strong>Sam<\/strong>/);
  const comment = shareHistoryCommentCardHtml({
    author_id: "u-alex",
    author_name: "Alex",
    avatar_url: "/avatars/alex.png",
    t: 4,
    text: "nice cut",
  });
  assert.match(comment, /data-share-profile-id="u-alex"/);
  assert.match(comment, /nice cut/);
  assert.match(comment, /data-share-seek="4"/);
  const guest = shareHistoryAvatarHtml({ user_name: "Guest" });
  assert.match(guest, /<span class="sv-avatar sv-avatar--initial"/);
  assert.doesNotMatch(guest, /data-share-profile-id/);
  const owner = shareHistoryOwnerEntry({
    generated_by: { user_id: "u-own", display_name: "Sam", avatar_url: "/a.png" },
  });
  assert.equal(owner.user_id, "u-own");
  assert.match(shareHistoryWhoRowHtml(owner, { prefix: "Shared by" }), /Shared by/);
});

test("unsigned add/message returns to the share History profile", () => {
  assert.equal(
    shareHistorySignInReturnTo({
      pathname: "/share/QHGr7Cz1E0_1sVxA4KAnINjg",
      userId: "u-sam",
      intent: "friend",
    }),
    "/share/QHGr7Cz1E0_1sVxA4KAnINjg?open_history=1&profile=u-sam&profile_intent=friend",
  );
  assert.equal(SHARE_HISTORY_PROFILE_KIND, "share-history-profile");
});

test("share viewer, profile popup, and studio bounce-back keep existing social APIs", () => {
  assert.match(shareViewer, /share-history-authors\.js\?v=20260915-histprof1/);
  assert.match(shareViewer, /bindShareHistoryProfileClicks/);
  assert.match(shareViewer, /openMarketplaceMessages/);
  assert.match(shareViewer, /marketplace-messages\.js/);
  assert.match(shareViewer, /\/api\/social\/friends/);
  assert.match(shareViewer, /SHARE_HISTORY_PROFILE_KIND/);
  assert.match(shareViewer, /onNeedAuth/);
  assert.match(shareViewer, /shareHistoryOwnerEntry/);
  assert.match(shareHtml, /20260915-histprof1/);
  assert.match(shareHtml, /sv-avatar--profile/);
  assert.match(profileJs, /onNeedAuth/);
  assert.match(profileJs, /\/api\/social\/friends/);
  assert.match(profileJs, /data-profile-friend/);
  assert.match(profileJs, /data-profile-message/);
  assert.match(app, /share-history-profile/);
  assert.match(app, /location\.assign\(dest\)/);
});

test("history profile click binder opens the author id", () => {
  const documentRef = globalThis.document;
  if (typeof documentRef === "undefined") return;
  const root = documentRef.createElement("div");
  root.innerHTML = shareHistoryWhoRowHtml({ user_id: "u1", user_name: "Sam" });
  const opened = [];
  bindShareHistoryProfileClicks(root, (payload) => opened.push(payload));
  root.querySelector("[data-share-profile-id]").click();
  assert.equal(opened[0].userId, "u1");
});
